async def populate_database():
    """Poblar la base de datos con palabras iniciales"""
    
    # Obtener URL de MongoDB
    mongodb_url = os.getenv("MONGODB_URL")
    if not mongodb_url:
        print("❌ Error: MONGODB_URL no encontrada en .env")
        return
    
    print("🔌 Conectando a MongoDB...")
    client = AsyncIOMotorClient(mongodb_url)
    db = client.impostor_game
    
    try:
        # Verificar conexión
        await client.admin.command('ping')
        print("✅ Conectado a MongoDB!")
        
        # Eliminar palabras existentes automáticamente
        existing_count = await db.words.count_documents({})
        
        if existing_count > 0:
            result = await db.words.delete_many({})
            print(f"🗑️  Eliminadas {result.deleted_count} palabra(s) anteriores")
        
        # Agregar palabras
        print(f"\n📝 Agregando {len(INITIAL_WORDS)} palabras a la base de datos...")
        print("⏳ Esto puede tomar unos segundos...")
        
        words_to_insert = []
        for word_data in INITIAL_WORDS:
            word_doc = {
                "word_id": str(uuid.uuid4()),
                "word": word_data["word"],
                "hint": word_data["hint"],
                "category": word_data.get("category"),
                "difficulty": word_data.get("difficulty", "medium")
            }
            words_to_insert.append(word_doc)
        
        result = await db.words.insert_many(words_to_insert)
        print(f"✅ {len(result.inserted_ids)} palabras agregadas exitosamente!")
        
        # Mostrar estadísticas
        print("\n📊 Estadísticas:")
        categories = {}
        difficulties = {}
        
        for word in words_to_insert:
            cat = word.get("category", "Sin categoría")
            diff = word.get("difficulty", "medium")
            categories[cat] = categories.get(cat, 0) + 1
            difficulties[diff] = difficulties.get(diff, 0) + 1
        
        print("\nPor categoría:")
        for cat, count in sorted(categories.items()):
            print(f"  • {cat}: {count}")
        
        print("\nPor dificultad:")
        for diff, count in sorted(difficulties.items()):
            print(f"  • {diff}: {count}")
        
        print("\n🎉 ¡Base de datos poblada exitosamente!")
        
    except Exception as e:
        print(f"❌ Error: {str(e)}")
    finally:
        client.close()
        print("\n🔌 Conexión cerrada")


if __name__ == "__main__":
    print("=" * 60)
    print("🎮 POBLADOR DE BASE DE DATOS - JUEGO DEL IMPOSTOR")
    print("=" * 60)
    asyncio.run(populate_database())
